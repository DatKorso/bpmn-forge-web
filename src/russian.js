function translate(text, replacements = {}) {
  const suffix = ' (non-interrupting)';
  const nonInterrupting = text.endsWith(suffix);
  const key = nonInterrupting ? text.slice(0, -suffix.length) : text;
  const message = Object.hasOwn(messages, key) ? messages[key] : undefined;
  const localized = message && nonInterrupting ? `${message} (без прерывания)` : message ?? text;
  return localized.replace(
    /\{([^}]+)\}/g, (match, key) => replacements[key] ?? match
  );
}

export default { translate: ['value', translate] };
